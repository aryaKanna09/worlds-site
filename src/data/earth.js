export const isLand = (latDeg, lonDeg) => {
  const row = Math.min(35, Math.max(0, Math.floor((90 - latDeg) / 5)));
  if (row === 31) {
    // Antarctic coastline: a sparse ring.
    return Math.floor((((lonDeg + 180) / 5) % 72 + 72) % 72) % 2 === 0;
  }
  const segments = LAND_SEGMENTS[row];
  if (!segments) return false;
  const col = (Math.floor((lonDeg + 180) / 5) % 72 + 72) % 72;
  return segments.some(([a, b]) => col >= a && col < b);
};
